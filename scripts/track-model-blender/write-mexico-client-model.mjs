import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const round = (value, digits = 4) => Number(value.toFixed(digits));

export async function writeMexicoClientModel({ configPath, metadataPath }) {
  const [config, metadata, asset, preview] = await Promise.all([
    readFile(configPath, "utf8").then(JSON.parse),
    readFile(metadataPath, "utf8").then(JSON.parse),
    readFile(path.join(root, "public/f1/tracks/3d/mexico.glb")),
    readFile(path.join(root, "public/f1/tracks/3d/mexico-preview.webp")),
  ]);
  const line = config.model.centerline;
  const cumulative = [0];
  for (let index = 1; index < line.length; index += 1) {
    cumulative.push(cumulative.at(-1) + Math.hypot(line[index][0] - line[index - 1][0],
      line[index][1] - line[index - 1][1]));
  }
  const total = cumulative.at(-1);
  const profile = metadata.elevationProfile;
  const points = profile.map(({ distanceMeters, elevationMeters }, index) => {
    const distance = Math.max(0, Math.min(distanceMeters, total));
    const found = cumulative.findIndex((position) => position >= distance);
    const hi = found < 0 ? line.length - 1 : Math.max(1, found);
    const span = cumulative[hi] - cumulative[hi - 1];
    const blend = span > 0 ? (distance - cumulative[hi - 1]) / span : 0;
    const position = line[hi].map((value, axis) => line[hi - 1][axis] + (value - line[hi - 1][axis]) * blend);
    return [round(index / (profile.length - 1), 6),
      round(position[0] - config.model.center.x), round(position[1] - config.model.center.y),
      round(elevationMeters * 10)];
  });
  points.at(-1).splice(0, 4, 1, ...points[0].slice(1));
  const slopes = profile.slice(1).map((point, index) => {
    const distance = point.distanceMeters - profile[index].distanceMeters;
    return distance > 0 ? (point.elevationMeters - profile[index].elevationMeters) / distance * 100 : 0;
  });
  const turns = config.model.turns.map(({ number, distanceMeters }) => ({
    number, progress: round(distanceMeters / total, 6),
  }));
  const data = {
    circuitName: "Autódromo Hermanos Rodríguez",
    lapLengthKm: 4.304,
    elevationChangeM: round(metadata.elevationsMeters.high - metadata.elevationsMeters.low, 1),
    maxDownhillPercent: round(Math.abs(Math.min(...slopes)), 1),
    maxUphillPercent: round(Math.max(...slopes), 1),
    points,
    turns,
    sectorBreaks: metadata.sectorBoundaryDistancesMeters.map((distance) => round(distance / total, 6)),
    speedTrapProgress: round(config.officialControlPoints.speedTrapDistanceMeters / total, 6),
  };
  const { width, depth } = metadata.boundsMeters;
  const { low, high } = metadata.elevationsMeters;
  const terrain = {
    attribution: Array.from(new Set(metadata.sourceManifest.sources.map((source) => source.attribution))).join(" · "),
    attributionUrl: "/f1/tracks/3d/mexico-metadata.json",
    bounds: { minX: -width / 2, minY: -depth / 2, maxX: width / 2, maxY: depth / 2 },
    columns: 2, rows: 2,
    elevationMinM: low,
    elevationMaxM: high,
    values: [[low, high], [high, low]],
  };
  const revision = (buffer) => createHash("sha256").update(buffer).digest("hex").slice(0, 12);
  const model = {
    id: "mexico",
    aliases: ["autódromo hermanos rodríguez", "autodromo hermanos rodriguez", "hermanos rodríguez", "hermanos rodriguez",
      "rodriguez", "mexico city", "mexico", "мехико", "мексика", "эрманос родригес",
      "mexico city grand prix", "mexican grand prix", "гран-при мехико", "гран-при мексики"],
    data: "__DATA__",
    terrain: "__TERRAIN__",
    camera: { centerY: 0, rotationDeg: 0, scale: 1, tiltDeg: 10, verticalExaggeration: 1 },
    rendering: { contourIntervalM: 5, curbTurnNumbers: turns.map((turn) => turn.number),
      gravelTurnNumbers: [], runoffTurnNumbers: [],
      turnLabelOffsets: Object.fromEntries(turns.map((turn) => [turn.number, [0, 0]])) },
    webgl: {
      assetPath: `/f1/tracks/3d/mexico.glb?v=${revision(asset)}`,
      previewPath: `/f1/tracks/3d/mexico-preview.webp?v=${revision(preview)}`,
      turnCount: 17,
      elevationDatumLabel: "м",
      elevationApproximate: metadata.elevationApproximate === true,
      camera: { fitWidth: round(Math.max(width * 2.25, depth * 2.8)),
        narrowFitWidth: round(Math.max(width * 2.45, depth * 2.8)),
        fitHeight: round(depth * 2), lookAtY: round((low + high) / 2), radius: round(Math.max(width, depth) * 1.2) },
    },
  };
  await writeFile(path.join(root, "src/data/mexico-model.ts"),
    `import type { TrackModelDefinition } from "@/data/track-model-types";\n\n` +
    `// Generated by pnpm track:3d:build mexico. Native UTM metres, no vertical exaggeration.\n` +
    `export const MEXICO_MODEL = ${JSON.stringify(data, null, 2)} as const;\n\n` +
    `export const MEXICO_TERRAIN = ${JSON.stringify(terrain, null, 2)} as const;\n\n` +
    `export const MEXICO_TRACK_MODEL = ${JSON.stringify(model, null, 2)
      .replace('"__DATA__"', "MEXICO_MODEL")
      .replace('"__TERRAIN__"', "MEXICO_TERRAIN")} satisfies TrackModelDefinition;\n`);
}
