import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { cumulativeDistances, sampleLine } from "./sepang-geometry.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");

export async function writeSepangClientModel({ configPath, metadataPath }) {
  const [config, metadata, asset, preview] = await Promise.all([
    readFile(configPath, "utf8").then(JSON.parse),
    readFile(metadataPath, "utf8").then(JSON.parse),
    readFile(path.join(root, "public/f1/tracks/3d/sepang.glb")),
    readFile(path.join(root, "public/f1/tracks/3d/sepang-preview.webp")),
  ]);
  const round = (value, digits = 4) => Number(value.toFixed(digits));
  const total = metadata.lapLength.geometryMeters;
  const profile = metadata.elevationProfile;
  const cumulative = cumulativeDistances(config.model.centerline);
  const points = profile.map(({ distanceMeters, elevationMeters }, i) => {
    const p = sampleLine(config.model.centerline, cumulative, distanceMeters);
    return [round(i / (profile.length - 1), 6), round(p[0] - config.model.center.x), round(p[1] - config.model.center.y), round(elevationMeters * 10)];
  });
  points.at(-1).splice(0, 4, 1, ...points[0].slice(1));
  const slopes = profile.slice(1).map((p, i) => (p.elevationMeters - profile[i].elevationMeters) / (p.distanceMeters - profile[i].distanceMeters) * 100);
  const turns = config.model.turns.map(({ number, distanceMeters }) => ({ number, progress: round(distanceMeters / total, 6) }));
  const data = {
    circuitName: "Sepang International Circuit", lapLengthKm: 5.543,
    elevationChangeM: round(metadata.elevationsMeters.high - metadata.elevationsMeters.low, 1),
    maxDownhillPercent: round(Math.abs(Math.min(...slopes)), 1), maxUphillPercent: round(Math.max(...slopes), 1),
    points, turns, sectorBreaks: metadata.sectorBoundaryDistancesMeters.map((d) => round(d / total, 6)),
    speedTrapProgress: round((config.model.turns[14].distanceMeters - 207) / total, 6),
  };
  const terrain = {
    attribution: "© OpenStreetMap · Copernicus Sentinel-2, 15.08.2026 · высоты GLO-30, приблизительные · разметка FIA 2017",
    attributionUrl: "/f1/tracks/3d/sepang-metadata.json",
    bounds: { minX: -1000, minY: -700, maxX: 1000, maxY: 700 }, columns: 2, rows: 2,
    elevationMinM: metadata.elevationsMeters.low, elevationMaxM: metadata.elevationsMeters.high,
    values: [[metadata.elevationsMeters.low, metadata.elevationsMeters.high], [metadata.elevationsMeters.high, metadata.elevationsMeters.low]],
  };
  const revision = createHash("sha256").update(asset).digest("hex").slice(0, 12);
  const previewRevision = createHash("sha256").update(preview).digest("hex").slice(0, 12);
  const model = {
    id: "sepang", aliases: ["sepang international circuit", "sepang", "сепанг", "malaysian grand prix", "гран-при малайзии", "bahrain grand prix in malaysia", "kuala lumpur", "куала лумпур"],
    camera: { centerY: 0, rotationDeg: 0, scale: 1, tiltDeg: 10, verticalExaggeration: 1 },
    data: "__DATA__", terrain: "__TERRAIN__",
    rendering: { contourIntervalM: 5, curbTurnNumbers: turns.map((t) => t.number), gravelTurnNumbers: [], runoffTurnNumbers: [], turnLabelOffsets: Object.fromEntries(turns.map((t) => [t.number, [0, 0]])) },
    webgl: { assetPath: `/f1/tracks/3d/sepang.glb?v=${revision}`, previewPath: `/f1/tracks/3d/sepang-preview.webp?v=${previewRevision}`, turnCount: 15, elevationDatumLabel: "м DEM", elevationApproximate: true, camera: { fitWidth: 2600, fitHeight: 1550, lookAtY: 24, radius: 2100 } },
  };
  const output = `import type { TrackModelDefinition } from "@/data/track-model-types";\n\n// Generated by pnpm track:3d:build sepang. Metre geometry; approximate Copernicus DSM elevations.\nexport const SEPANG_MODEL = ${JSON.stringify(data, null, 2)} as const;\n\nexport const SEPANG_TERRAIN = ${JSON.stringify(terrain, null, 2)} as const;\n\nexport const SEPANG_TRACK_MODEL = ${JSON.stringify(model, null, 2).replace('"__DATA__"', "SEPANG_MODEL").replace('"__TERRAIN__"', "SEPANG_TERRAIN")} satisfies TrackModelDefinition;\n`;
  await writeFile(path.join(root, "src/data/sepang-model.ts"), output);
}
