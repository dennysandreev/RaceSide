import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const round = (value, digits = 4) => Number(value.toFixed(digits));

export async function writeShanghaiClientModel({ configPath, metadataPath }) {
  const [config, metadata, asset, preview] = await Promise.all([
    readFile(configPath, "utf8").then(JSON.parse),
    readFile(metadataPath, "utf8").then(JSON.parse),
    readFile(path.join(root, "public/f1/tracks/3d/shanghai.glb")),
    readFile(path.join(root, "public/f1/tracks/3d/shanghai-preview.webp")),
  ]);
  const line = config.model.centerline;
  const cumulative = [0];
  for (let i = 1; i < line.length; i += 1) {
    cumulative.push(cumulative.at(-1) + Math.hypot(line[i][0] - line[i - 1][0], line[i][1] - line[i - 1][1]));
  }
  const total = cumulative.at(-1);
  const profile = metadata.elevationProfile;
  const points = profile.map(({ distanceMeters, elevationMeters }, index) => {
    const hi = Math.max(1, cumulative.findIndex((distance) => distance >= Math.min(distanceMeters, total)));
    const blend = Math.min(1, (distanceMeters - cumulative[hi - 1]) / (cumulative[hi] - cumulative[hi - 1]));
    const position = line[hi].map((value, axis) => line[hi - 1][axis] + (value - line[hi - 1][axis]) * blend);
    return [round(index / (profile.length - 1), 6), round(position[0] - config.model.center.x),
      round(position[1] - config.model.center.y), round(elevationMeters * 10)];
  });
  points.at(-1).splice(0, 4, 1, ...points[0].slice(1));
  const slopes = profile.slice(1).map((point, index) =>
    (point.elevationMeters - profile[index].elevationMeters) / (point.distanceMeters - profile[index].distanceMeters) * 100);
  const turns = config.model.turns.map(({ number, distanceMeters }) => ({ number, progress: round(distanceMeters / total, 6) }));
  const data = {
    circuitName: "Shanghai International Circuit", lapLengthKm: 5.451,
    elevationChangeM: round(metadata.elevationsMeters.high - metadata.elevationsMeters.low, 1),
    maxDownhillPercent: round(Math.abs(Math.min(...slopes)), 1), maxUphillPercent: round(Math.max(...slopes), 1),
    points, turns,
    sectorBreaks: metadata.sectorBoundaryDistancesMeters.map((distance) => round(distance / total, 6)),
    speedTrapProgress: round(config.officialControlPoints.speedTrapDistanceMeters / total, 6),
  };
  const terrain = {
    attribution: "© OpenStreetMap · Planet Labs · OpenGeoHub · FIA 2026",
    attributionUrl: "/f1/tracks/3d/shanghai-metadata.json",
    bounds: { minX: -870, minY: -810, maxX: 870, maxY: 810 }, columns: 2, rows: 2,
    elevationMinM: metadata.elevationsMeters.low, elevationMaxM: metadata.elevationsMeters.high,
    values: [[metadata.elevationsMeters.low, metadata.elevationsMeters.high],
      [metadata.elevationsMeters.high, metadata.elevationsMeters.low]],
  };
  const revision = (buffer) => createHash("sha256").update(buffer).digest("hex").slice(0, 12);
  const model = {
    id: "shanghai",
    aliases: ["shanghai international circuit", "shanghai circuit", "shanghai", "шанхай", "chinese grand prix", "гран-при китая"],
    data: "__DATA__", terrain: "__TERRAIN__",
    camera: { centerY: 0, rotationDeg: 0, scale: 1, tiltDeg: 10, verticalExaggeration: 1 },
    rendering: { contourIntervalM: 5, curbTurnNumbers: turns.map((turn) => turn.number),
      gravelTurnNumbers: [], runoffTurnNumbers: [], turnLabelOffsets: Object.fromEntries(turns.map((turn) => [turn.number, [0, 0]])) },
    webgl: {
      assetPath: `/f1/tracks/3d/shanghai.glb?v=${revision(asset)}`,
      previewPath: `/f1/tracks/3d/shanghai-preview.webp?v=${revision(preview)}`,
      turnCount: 16, elevationDatumLabel: "м над уровнем моря", elevationApproximate: true,
      camera: { fitWidth: 1950, narrowFitWidth: 2100, fitHeight: 1800, lookAtY: 15, radius: 2100 },
    },
  };
  await writeFile(path.join(root, "src/data/shanghai-model.ts"),
    `import type { TrackModelDefinition } from "@/data/track-model-types";\n\n` +
    `// Generated by pnpm track:3d:build shanghai. UTM 51N metres, GEDTM30 heights, no vertical exaggeration.\n` +
    `export const SHANGHAI_MODEL = ${JSON.stringify(data, null, 2)} as const;\n\n` +
    `export const SHANGHAI_TERRAIN = ${JSON.stringify(terrain, null, 2)} as const;\n\n` +
    `export const SHANGHAI_TRACK_MODEL = ${JSON.stringify(model, null, 2).replace('"__DATA__"', "SHANGHAI_MODEL").replace('"__TERRAIN__"', "SHANGHAI_TERRAIN")} satisfies TrackModelDefinition;\n`);
}
